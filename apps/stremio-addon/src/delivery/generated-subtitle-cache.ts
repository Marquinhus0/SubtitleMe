export interface CachedVttEntry {
  token: string;
  vttContent: string;
  byteLength: number;
  createdAt: number;
  expiresAt: number;
  sessionScope: string;
  fingerprint: string;
  sourceIds: readonly string[];
  cueCount: number;
  syncPercent?: number;
}

export interface GeneratedSubtitleCacheOptions {
  ttlMs?: number;
  maxEntries?: number;
  maxTotalBytes?: number;
  nowProvider?: () => number;
}

export interface CacheEntryMetadata {
  sessionScope?: string;
  fingerprint?: string;
  sourceIds?: readonly string[];
  cueCount?: number;
  syncPercent?: number;
}

/**
 * Bounded, session-scoped in-memory TTL/LRU cache for generated combined WebVTT files.
 *
 * Security properties:
 * - Tokens are opaque random access handles (generated by SubtitleFileService), never predictable.
 * - Entries are scoped by `sessionScope` so different sessions never share tokens or collide.
 * - Tracks `sourceIds` so deleting or updating a local subtitle immediately invalidates
 *   all derived combined VTT entries.
 * - Enforces strict entry count (default 200), byte budget (default 20 MB), and TTL (default 15 min).
 */
export class GeneratedSubtitleCache {
  private readonly ttlMs: number;
  private readonly maxEntries: number;
  private readonly maxTotalBytes: number;
  private readonly now: () => number;

  private readonly entries = new Map<string, CachedVttEntry>();
  /** Maps `${sessionScope}::${fingerprint}` -> opaque token for same-session reuse. */
  private readonly scopeFingerprintIndex = new Map<string, string>();
  private totalBytes = 0;

  public constructor(options: GeneratedSubtitleCacheOptions = {}) {
    this.ttlMs = options.ttlMs ?? 15 * 60 * 1000; // 15 minutes default
    this.maxEntries = options.maxEntries ?? 200;
    this.maxTotalBytes = options.maxTotalBytes ?? 20 * 1024 * 1024; // 20 MB cap
    this.now = options.nowProvider ?? (() => Date.now());
  }

  private buildScopeKey(sessionScope: string, fingerprint: string): string {
    return `${sessionScope}::${fingerprint}`;
  }

  public get(token: string, expectedSessionScope?: string): CachedVttEntry | null {
    const entry = this.entries.get(token);
    if (!entry) return null;

    if (this.now() >= entry.expiresAt) {
      this.delete(token);
      return null;
    }

    if (expectedSessionScope !== undefined && entry.sessionScope !== expectedSessionScope) {
      return null;
    }

    // Refresh LRU order
    this.entries.delete(token);
    this.entries.set(token, entry);
    return entry;
  }

  public getByFingerprint(sessionScope: string, fingerprint: string): CachedVttEntry | null {
    const scopeKey = this.buildScopeKey(sessionScope, fingerprint);
    const token = this.scopeFingerprintIndex.get(scopeKey);
    if (!token) return null;
    const entry = this.get(token, sessionScope);
    if (!entry) {
      this.scopeFingerprintIndex.delete(scopeKey);
      return null;
    }
    return entry;
  }

  public set(
    token: string,
    vttContent: string,
    metadata: CacheEntryMetadata = {},
  ): CachedVttEntry {
    this.purgeExpired();

    const byteLength = Buffer.byteLength(vttContent, 'utf-8');
    if (byteLength > this.maxTotalBytes) {
      throw new Error('Generated WebVTT exceeds cache maximum byte limit.');
    }

    if (this.entries.has(token)) {
      this.delete(token);
    }

    // Evict oldest LRU entries while over count or byte budget
    while (
      this.entries.size >= this.maxEntries ||
      this.totalBytes + byteLength > this.maxTotalBytes
    ) {
      const oldestKey = this.entries.keys().next().value;
      if (oldestKey === undefined) break;
      this.delete(oldestKey);
    }

    const sessionScope = metadata.sessionScope ?? 'default';
    const fingerprint = metadata.fingerprint ?? token;
    const sourceIds = metadata.sourceIds ? [...metadata.sourceIds] : [];
    const cueCount = metadata.cueCount ?? -1;

    const timestamp = this.now();
    const entry: CachedVttEntry = {
      token,
      vttContent,
      byteLength,
      createdAt: timestamp,
      expiresAt: timestamp + this.ttlMs,
      sessionScope,
      fingerprint,
      sourceIds,
      cueCount,
      ...(metadata.syncPercent !== undefined ? { syncPercent: metadata.syncPercent } : {}),
    };

    this.entries.set(token, entry);
    this.scopeFingerprintIndex.set(this.buildScopeKey(sessionScope, fingerprint), token);
    this.totalBytes += byteLength;
    return entry;
  }

  public delete(token: string): boolean {
    const existing = this.entries.get(token);
    if (!existing) return false;
    this.entries.delete(token);
    const scopeKey = this.buildScopeKey(existing.sessionScope, existing.fingerprint);
    if (this.scopeFingerprintIndex.get(scopeKey) === token) {
      this.scopeFingerprintIndex.delete(scopeKey);
    }
    this.totalBytes = Math.max(0, this.totalBytes - existing.byteLength);
    return true;
  }

  /**
   * Immediately invalidates all derived VTT entries that depended on a given sourceId.
   * Called when a user deletes or replaces a local subtitle file in Companion.
   */
  public invalidateBySourceId(sourceId: string): number {
    let removed = 0;
    for (const [token, entry] of this.entries.entries()) {
      if (entry.sourceIds.includes(sourceId)) {
        this.delete(token);
        removed += 1;
      }
    }
    return removed;
  }

  /**
   * Immediately invalidates all cached VTT entries belonging to a specific session scope.
   */
  public invalidateBySession(sessionScope: string): number {
    let removed = 0;
    for (const [token, entry] of this.entries.entries()) {
      if (entry.sessionScope === sessionScope) {
        this.delete(token);
        removed += 1;
      }
    }
    return removed;
  }

  public purgeExpired(): number {
    const current = this.now();
    let removed = 0;
    for (const [token, entry] of this.entries.entries()) {
      if (current >= entry.expiresAt) {
        this.delete(token);
        removed += 1;
      }
    }
    return removed;
  }

  public size(): number {
    this.purgeExpired();
    return this.entries.size;
  }

  public getTotalBytes(): number {
    this.purgeExpired();
    return this.totalBytes;
  }

  public clear(): void {
    this.entries.clear();
    this.scopeFingerprintIndex.clear();
    this.totalBytes = 0;
  }
}
